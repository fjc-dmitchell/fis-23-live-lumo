package gov.fjc.fis.view.dashboard.jitfdashboard;


import com.vaadin.flow.router.Route;
import gov.fjc.fis.entity.dto.JitfTransferDto;
import gov.fjc.fis.service.JitfTransferService;
import io.jmix.core.LoadContext;
import io.jmix.flowui.model.CollectionLoader;
import io.jmix.flowui.view.*;
import org.springframework.beans.factory.annotation.Autowired;

import java.util.List;

/**
 * Dashboard view that displays the historical financial activity of the
 * Judiciary Information Technology Fund (JITF).
 *
 * <p>The view presents a year-by-year summary of JITF activity, including
 * deposits, expenses, carry-forward amounts, and ending balances for each
 * fiscal year in which JITF funds have been used. This information allows
 * users to review the long-term financial history of the fund and monitor how
 * available balances have changed over time.
 *
 * <p>The dashboard loads and displays report data generated by
 * {@link JitfTransferService}, providing a consolidated view of JITF financial
 * activity without requiring users to review individual transfer or expense
 * records.
 *
 * @author Doug Mitchell
 */
@Route(value = "jitf-dashboard", layout = DefaultMainViewParent.class)
@ViewController(id = "fis_JitfDashboardView")
@ViewDescriptor(path = "jitf-dashboard-view.xml")
public class JitfDashboardView extends StandardView {
    @Autowired
    private JitfTransferService jitfTransferService;
    @ViewComponent
    private CollectionLoader<JitfTransferDto> jitfTransferDtoesDl;

    @Subscribe
    protected void onBeforeShow(final BeforeShowEvent event) {
        jitfTransferDtoesDl.load();
    }

    @Install(to = "jitfTransferDtoesDl", target = Target.DATA_LOADER)
    protected List<JitfTransferDto> jitfTransferDtoesDlLoadDelegate(final LoadContext<JitfTransferDto> loadContext) {
        return jitfTransferService.generateReport();
    }
}